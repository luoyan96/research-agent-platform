export function recoveryHint(code: string): string {
  if (code === 'RATE_LIMITED') return '请求过于频繁，请稍后再试，不要连续点击。若仍无法登录，请联系管理员；不要发送密码。';
  if (['MODEL_UNAVAILABLE','CAPABILITY_UNAVAILABLE'].includes(code)) return 'AI 当前不可用。可以重试原请求；若改为手工安排，请先明确放弃原请求，再返回需求入口选择“手工创建方案”。任务中仍可按权限人工交付。';
  if (['NETWORK_ERROR','SERVICE_UNAVAILABLE'].includes(code)) return '请先恢复与服务的连接，再读取最新状态；未决操作可重试同一请求，沿用原内容。不要把连接失败当作提交失败或成功。';
  if (code === 'UNAUTHENTICATED') return '请用同一账号重新登录后继续原输入或重试原请求。密码重置后需使用新密码；账号停用请联系管理员。主动退出或换账号会清空本地输入。';
  if (code === 'PENDING_INTENT') return '上一操作尚未确认。请重试同一请求，或明确放弃后再保存新安排；放弃本地请求不会取消已被服务接受的运行。';
  if (['CONTRACT_MISMATCH','INVALID_RESPONSE'].includes(code)) return '请读取最新状态；若仍失败，请联系维护者核对页面与服务。页面未把这次响应当作成功。';
  return '';
}
